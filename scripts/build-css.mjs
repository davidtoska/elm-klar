#!/usr/bin/env node
// Builds the stylesheet of the package.
//
//   node scripts/build-css.mjs           write css/klar.css and src/Klar/Internal/Css.elm
//   node scripts/build-css.mjs --check   fail if those two files are out of date
//
// Sources: css/src/index.css lists the files (as @import lines) in bundle order.
//
// css/klar.css            the bundle with comments, for applications that link a file
// src/Klar/Internal/Css.elm   the same rules without comments and indentation, as an Elm
//                         string. `Klar.stylesheet` renders it, so an application needs
//                         no build step to use the package.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'css', 'src');
const bundleFile = path.join(root, 'css', 'klar.css');
const elmFile = path.join(root, 'src', 'Klar', 'Internal', 'Css.elm');
const check = process.argv.includes('--check');

const pkg = JSON.parse(fs.readFileSync(path.join(root, 'elm.json'), 'utf8'));

// ---- the file order -------------------------------------------------------------------------

const manifest = fs.readFileSync(path.join(srcDir, 'index.css'), 'utf8');
const files = [...manifest.matchAll(/@import\s+url\("([^"]+)"\)\s*;/g)].map((m) => m[1]);
if (files.length === 0) throw new Error('css/src/index.css lists no files');

const sources = files.map((name) => {
  const text = fs
    .readFileSync(path.join(srcDir, name), 'utf8')
    .replace(/^﻿/, '') // a byte order mark in the middle of the bundle would disable the next rule
    .replace(/\r\n/g, '\n');
  if (/@import/.test(text)) throw new Error(`${name} contains @import; list files in index.css instead`);
  return { name, text: text.replace(/\s+$/, '') + '\n' };
});

// ---- the readable bundle --------------------------------------------------------------------------

const banner = `/*!
 * Klar ${pkg.version} - ${pkg.summary}.
 * https://github.com/${pkg.name}
 * ${pkg.license} license. Generated by scripts/build-css.mjs from css/src/*.css: do not edit.
 */
`;
const bundle =
  banner + '\n' + sources.map((s) => `/* ==== ${s.name} ==== */\n\n${s.text}`).join('\n');

// ---- light minification -------------------------------------------------------------------------------
// Removes comments and indentation. It never touches the inside of strings, and keeps
// the spaces around ':' and combinators, which can change the meaning of selectors.

function minify(css) {
  let out = '';
  let i = 0;
  const n = css.length;
  let pendingSpace = false;
  let depth = 0;

  const emit = (text) => {
    if (pendingSpace) {
      const last = out[out.length - 1];
      const first = text[0];
      // spaces next to these characters carry no meaning
      const dropBefore = '{};,';
      const dropAfter = '{};,';
      if (last !== undefined && !dropAfter.includes(last) && !dropBefore.includes(first)) out += ' ';
      pendingSpace = false;
    }
    out += text;
  };

  while (i < n) {
    const c = css[i];
    if (c === '/' && css[i + 1] === '*') {
      const end = css.indexOf('*/', i + 2);
      if (end < 0) throw new Error('unterminated comment');
      i = end + 2;
      pendingSpace = true;
      continue;
    }
    if (c === '"' || c === "'") {
      let j = i + 1;
      while (j < n && css[j] !== c) {
        if (css[j] === '\\') j++;
        j++;
      }
      if (j >= n) throw new Error('unterminated string');
      emit(css.slice(i, j + 1));
      i = j + 1;
      continue;
    }
    if (/\s/.test(c)) {
      pendingSpace = true;
      i++;
      continue;
    }
    if (c === '}') {
      // the last ';' of a block is not needed
      if (out.endsWith(';')) out = out.slice(0, -1);
      pendingSpace = false;
      depth--;
      out += '}';
      if (depth === 0) out += '\n';
      i++;
      continue;
    }
    if (c === '{') depth++;
    emit(c);
    i++;
  }
  if (depth !== 0) throw new Error('unbalanced braces');
  return out.replace(/\n+/g, '\n');
}

const minified = minify(sources.map((s) => s.text).join('\n'));

// ---- the Elm module ---------------------------------------------------------------------------------------

if (minified.includes('"""')) throw new Error('the CSS contains """, which cannot be written as an Elm string');
const elmString = minified.replace(/\\/g, '\\\\');

const elm = `module Klar.Internal.Css exposing (css)

{-| The stylesheet of the package as one string.

Generated by \`scripts/build-css.mjs\` from \`css/src/*.css\`. Do not edit.

-}


{-| All rules of the library.
-}
css : String
css =
    """${elmString}"""
`;

// ---- write or check ------------------------------------------------------------------------------------------

function sameAsOnDisk(file, expected) {
  return fs.existsSync(file) && fs.readFileSync(file, 'utf8') === expected;
}

if (check) {
  const stale = [];
  if (!sameAsOnDisk(bundleFile, bundle)) stale.push(path.relative(root, bundleFile));
  if (!sameAsOnDisk(elmFile, elm)) stale.push(path.relative(root, elmFile));
  if (stale.length > 0) {
    console.error('Out of date: ' + stale.join(', ') + '\nRun: npm run build:css');
    process.exit(1);
  }
  console.log('css: up to date');
} else {
  fs.mkdirSync(path.dirname(bundleFile), { recursive: true });
  fs.mkdirSync(path.dirname(elmFile), { recursive: true });
  fs.writeFileSync(bundleFile, bundle, 'utf8');
  fs.writeFileSync(elmFile, elm, 'utf8');
  const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + ' KB';
  console.log(`css/klar.css ${kb(bundle)}, src/Klar/Internal/Css.elm ${kb(elm)} (${files.length} files)`);
}
