#!/usr/bin/env node
// Checks that every CSS class the Elm code uses has a rule in the stylesheet, so
// a renamed or misspelled class cannot silently lose its style.
//
//   node scripts/check-classes.mjs             check
//   node scripts/check-classes.mjs --update    rewrite scripts/class-hooks.txt
//
// Elm: string literals that start with "klar-" (a literal that ends in "-" or "_" is
// a prefix completed at run time, e.g. "klar-button--" ++ look).
// CSS: class selectors in the stylesheet modules, src/Klar/Internal/Css/*.elm.
//
// Some classes are only hooks: the markup has them but nothing is styled with them.
// They are listed in scripts/class-hooks.txt and are not reported.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function walk(dir, ext) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(p, ext));
    else if (entry.name.endsWith(ext)) out.push(p);
  }
  return out;
}

const cssClasses = new Set();
for (const file of walk(path.join(root, 'src', 'Klar', 'Internal', 'Css'), '.elm')) {
  const text = fs.readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of text.matchAll(/\.(klar-[a-zA-Z0-9_-]+)/g)) cssClasses.add(m[1]);
}

const used = new Map(); // class or prefix -> first location
const prefixes = new Map();
for (const file of walk(path.join(root, 'src'), '.elm')) {
  if (file.endsWith(path.join('Internal', 'Css.elm')) || file.includes(path.join('Internal', 'Css') + path.sep)) continue;
  const lines = fs.readFileSync(file, 'utf8').split('\n');
  lines.forEach((line, index) => {
    if (/^\s*--/.test(line)) return;
    for (const literal of line.matchAll(/"([^"\\]*klar-[^"\\]*)"/g)) {
      for (const word of literal[1].split(/\s+/)) {
        if (!word.startsWith('klar-')) continue;
        const where = `${path.relative(root, file)}:${index + 1}`;
        if (word.endsWith('-') || word.endsWith('_')) {
          if (!prefixes.has(word)) prefixes.set(word, where);
        } else if (/^klar-[a-zA-Z0-9_-]+$/.test(word) && !used.has(word)) used.set(word, where);
      }
    }
  });
}

const hooksFile = path.join(root, 'scripts', 'class-hooks.txt');
const hooks = new Set(
  fs.existsSync(hooksFile)
    ? fs.readFileSync(hooksFile, 'utf8').split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'))
    : [],
);

const missing = [];
for (const [name, where] of used) if (!cssClasses.has(name)) missing.push({ name, where });
for (const [prefix, where] of prefixes) {
  if (![...cssClasses].some((c) => c.startsWith(prefix))) missing.push({ name: prefix, where });
}

if (process.argv.includes('--update')) {
  const names = missing.map((m) => m.name).sort();
  fs.writeFileSync(
    hooksFile,
    '# CSS classes that the Elm code puts on elements but that have no rule of their own.\n' +
      '# They are hooks (structure, tests, future styling). Generated by: node scripts/check-classes.mjs --update\n' +
      names.join('\n') +
      '\n',
  );
  console.log(`wrote ${names.length} hooks to scripts/class-hooks.txt`);
  process.exit(0);
}

// One class, one owner: a bare class selector (`.klar-mark {`) that starts rules in two
// stylesheet modules is two components that picked the same name, and the later module
// silently restyles the earlier one's elements. Only the rules at the top level count:
// a rule inside `@media` or `@supports` (reduced motion, print, forced colors) is an
// override of a class that has its rules elsewhere, and any module may write one.
function topLevelSelectors(css) {
  const out = [];
  const open = []; // one entry per open block: true for an at-rule, false for a rule
  let prelude = '';
  let quote = null;
  for (const ch of css) {
    if (quote !== null) {
      if (ch === quote) quote = null;
      if (open.length === 0) prelude += ch;
      continue;
    }
    if (ch === '"' || ch === "'") {
      quote = ch;
      if (open.length === 0) prelude += ch;
    } else if (ch === '{') {
      const text = prelude.trim();
      const atRule = text.startsWith('@');
      if (!atRule && open.length === 0) out.push(text);
      open.push(atRule);
      prelude = '';
    } else if (ch === '}') {
      open.pop();
      prelude = '';
    } else if (ch === ';') {
      prelude = '';
    } else {
      prelude += ch;
    }
  }
  return out;
}

const owners = new Map();
const clashes = [];
for (const file of walk(path.join(root, 'src', 'Klar', 'Internal', 'Css'), '.elm')) {
  const name = path.basename(file);
  const source = fs.readFileSync(file, 'utf8');
  // the CSS is the one triple-quoted string of the module
  const start = source.indexOf('"""');
  const end = source.lastIndexOf('"""');
  if (start < 0 || end <= start) continue;
  const css = source.slice(start + 3, end).replace(/\/\*[\s\S]*?\*\//g, '');
  for (const selectors of topLevelSelectors(css)) {
    for (const selector of selectors.split(',').map((s) => s.trim())) {
      if (!/^\.klar-[a-zA-Z0-9_-]+$/.test(selector)) continue;
      const cls = selector.slice(1);
      const first = owners.get(cls);
      if (first === undefined) owners.set(cls, name);
      else if (first !== name) clashes.push(`${cls}: ${first} and ${name}`);
    }
  }
}
if (clashes.length > 0) {
  console.log(`${clashes.length} class(es) with rules of their own in two stylesheet modules:`);
  for (const c of clashes) console.log(`  - ${c}`);
  console.log('Give one of them another name.');
  process.exit(1);
}

const problems = missing.filter((m) => !hooks.has(m.name));
const stale = [...hooks].filter((h) => cssClasses.has(h) || (![...used.keys()].includes(h) && ![...prefixes.keys()].includes(h)));

if (problems.length > 0) {
  console.log(`${problems.length} class(es) without a CSS rule:`);
  for (const p of problems) console.log(`  - ${p.where}: ${p.name}`);
  console.log('Add the rule, or (if it is only a hook) run: node scripts/check-classes.mjs --update');
  process.exit(1);
}
if (stale.length > 0) console.log(`note: ${stale.length} entr${stale.length === 1 ? 'y' : 'ies'} in class-hooks.txt no longer needed: ${stale.join(', ')}`);
console.log(`classes: ok (${used.size} classes and ${prefixes.size} prefixes used, ${cssClasses.size} in the stylesheet, ${hooks.size} hooks)`);
